/** Dedicated static pages reuse the reviewed homepage case-study content. */
export const caseStudies = [
  { id: 'insurance-case', file: 'case-keylane.html', image: 'case-keylane.jpg', lines: ['Keylane', 'Insurance software'], focus: 'Java · REST APIs · SOAP · SQL' },
  { id: 'fusion-project', file: 'case-fusion-almere-fc.html', image: 'case-fusion-almere-fc.jpg', lines: ['Fusion Almere FC', 'Club platform'], focus: 'Angular · Spring Boot · Supabase' },
  { id: 'energy-project', file: 'case-homewizard-energy.html', image: 'case-homewizard-energy.jpg', lines: ['HomeWizard Energy', 'Intelligence'], focus: 'Collection · Recovery · Energy history' },
  { id: 'aoc-project', file: 'case-advent-of-code.html', image: 'case-advent-of-code.jpg', lines: ['Advent of Code', 'Java puzzle toolkit'], focus: 'Java · Gradle · Testing' },
];

function escapeHtml(value) {
  return value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

export function renderCaseStudies(homepage, canonical) {
  const originalHead = homepage.match(/<head>([\s\S]*?)<\/head>/)[1];
  const navigation = homepage.match(/<header\b[\s\S]*?<\/header>/)[0].replaceAll('href="#', 'href="/#');
  const footer = homepage.match(/<footer\b[\s\S]*?<\/footer>/)[0]
    .replace('href="#home"', 'href="/#home"').replace('href="#home"', 'href="#main"');
  const scripts = homepage.match(/<script src="js\/scripts\.js[^" ]*" defer><\/script>/)[0];
  return caseStudies.map((project, index) => {
    const adjacentLink = (item, direction) => item
      ? `<a class="case-adjacent-link case-${direction}" href="${item.file}" rel="${direction}"><span>${direction === 'prev' ? '← Previous project' : 'Next project →'}</span><strong>${escapeHtml(item.lines[0])}</strong></a>`
      : '';
    const adjacent = adjacentLink(caseStudies[index - 1], 'prev') + adjacentLink(caseStudies[index + 1], 'next');
    const article = homepage.match(new RegExp(`<article[^>]*id="${project.id}"[\\s\\S]*?</article>`))?.[0];
    if (!article) throw new Error(`Missing case-study source: ${project.id}`);
    const title = article.match(/<h3>([\s\S]*?)<\/h3>/)[1];
    const description = article.match(/<p>([\s\S]*?)<\/p>/)[1].replace(/\s+/g, ' ').trim();
    const url = new URL(project.file, canonical).href;
    const image = new URL('assets/img/' + project.image, canonical).href;
    let head = originalHead.replace(/<title>[\s\S]*?<\/title>/, `<title>${title} — Chidozie Nnachor</title>`)
      .replace(/<link rel="canonical" href="[^"]+">/, `<link rel="canonical" href="${url}">`);
    const values = {
      description, 'og:title': `${title} — Chidozie Nnachor`, 'og:description': description,
      'og:url': url, 'og:image': image, 'twitter:image': image,
      'og:image:alt': `${title} — Chidozie Nnachor’s portfolio`,
      'twitter:image:alt': `${title} — Chidozie Nnachor’s portfolio`,
    };
    for (const [key, value] of Object.entries(values)) {
      head = head.replace(new RegExp(`(<meta (?:name|property)="${key}" content=")[^"]*(">)`),
        (_, before, after) => before + escapeHtml(value) + after);
    }
    const content = article.replace(/<h3>([\s\S]*?)<\/h3>/, '<h1>$1</h1>')
      .replaceAll('<h4>', '<h2>').replaceAll('</h4>', '</h2>')
      .replace(/<details\b[^>]*>\s*<summary>[\s\S]*?<\/summary>/, '')
      .replace('</details>', '')
      .replace(/<div class="project-share">[\s\S]*?<\/div>/, '')
      .replaceAll('href="#', 'href="/#');
    return [project.file, `<!DOCTYPE html>
<!-- Generated by scripts/build-static.mjs from docs/partials/portfolio-section.html. -->
<html lang="en" class="theme-keylane">
<head>${head}</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  ${navigation}
  <main id="main" class="site-shell case-page" tabindex="-1">
    <nav aria-label="Breadcrumb" class="case-breadcrumb"><a class="text-link" href="/#portfolio">Work &amp; projects</a><span aria-hidden="true"> / </span><span aria-current="page">${title}</span></nav>
    ${content}
    <nav aria-label="More case studies" class="case-pagination">${adjacent}</nav>
    <div class="case-page-actions"><a class="text-link" href="/#${project.id}">Back to project overview</a><a class="text-link" href="/#contact">Discuss this project</a></div>
  </main>
  ${footer}
  ${scripts}
</body>
</html>
`];
  });
}
